using FAMS.Domain.Academy;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace FAMS.Infrastructure.Persistence.Configurations;

public class GroundConfiguration : IEntityTypeConfiguration<Ground>
{
    public void Configure(EntityTypeBuilder<Ground> builder)
    {
        builder.ToTable("Grounds");

        builder.HasKey(g => g.Id);

        builder.Property(g => g.Name)
            .IsRequired()
            .HasMaxLength(200);

        builder.Property(g => g.Description)
            .HasMaxLength(1000);
    }
}